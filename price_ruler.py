"""
Одна линейка для оценки и для проверки.

Зачем модуль. Арбитраж отбирает кандидатов по цене из прайс-листа csgotrader, а
подтверждает их живой ценой из /render/. Это ДВА РАЗНЫХ ЧИСЛА про один предмет:
прайс-лист даёт медиану состоявшихся продаж, /render/ — низ стакана. Второе
всегда ниже первого, потому что продажи идут по всему стакану, а не только с
его дна.

Пока этого не учитывали, отбор систематически поднимал наверх то, что проверку
не пройдёт. Замер по логу 2026-09-13 17:23, пятнадцать проверенных кандидатов:

    Skeleton Knife Doppler   оценка $900.00 -> на самом деле $850.00  (+6%)
    Sport Gloves Amphibious         $530.00 -> $398.95                (+33%)
    Specialist Gloves Sunburst      $294.15 -> $225.00                (+31%)
    StatTrak Shadow Daggers         $333.21 -> $239.82                (+39%)
    Nomad Knife Marble Fade         $335.12 -> $335.49                (0%)
    Glock Nuclear Garden             $92.36 -> $63.22                 (+46%)
    ...

Завышена оценка у четырнадцати из пятнадцати, медиана завышения 16%. Это
сходится с тем, что в репозитории уже было измерено раньше и записано как
RATIO_EXPLAINABLE_BIAS = 1.13 (20 предметов, 2026-08-28).

Арифметика последствий убийственная. Порог отбора 35%: кандидат с «оценочной
скидкой 40%» после снятия перекоса становится 27%. Из тех пятнадцати порог
прошёл ровно ОДИН, остальные легли в 19-34% — промахнулись на считанные
проценты и промахнулись систематически. Восемь живых запросов к Steam за
прогон тратились на заведомо обречённых кандидатов.

Теперь оценка приводится к линейке проверки перед отбором, а коэффициент не
выдумывается, а считается по факту: каждая проверка даёт пару «оценка /
реальность», их складываем и берём медиану.

ЧЕТЫРЕ ВЕЩИ, КОТОРЫЕ ЛЕГКО СЛОМАТЬ, ЕСЛИ ТРОГАТЬ ЭТОТ КОД.

1. Замеряем СЫРУЮ оценку, а не исправленную. Иначе получится обратная связь:
   исправленная оценка сходится с реальностью, коэффициент ползёт к единице и
   сам себя отменяет. Поэтому в паре всегда steam_price_raw.

2. Медиана, а не среднее. Одна битая запись в прайс-листе (расхождение в
   двадцать раз там встречается) утащила бы среднее куда угодно.

3. Отдельная корзина на каждый источник. Прайс-лист завышает, справка CSFloat
   занижает — это оценка площадки для СВОЕГО рынка. Одна медиана на обоих
   означала бы среднюю температуру по больнице.

4. Пока замеров мало, берём умолчание, а не единицу. Единица — это заведомо
   неверное «перекоса нет», и мы знаем, что он есть.

ОГОВОРКА про область применимости. Пятнадцать замеров сделаны почти целиком на
дорогих предметах — ножи, перчатки. Механизм перекоса (медиана продаж против
низа стакана) от цены не зависит, поэтому переносим на всё. Но у дешёвых
предметов расхождение прайс-листа со справкой CSFloat доходит до 2.4x, и это
уже НЕ перекос линейки, а настоящая разница рынков: в Steam платят кошельковыми
деньгами, которые оттуда не вывести, и за дешёвый ширпотреб там дают втрое.
Проверок по дешёвым предметам у нас пока нет. Если окажется, что коэффициент у
них другой, это будет видно по разбросу в describe() — тогда корзины надо будет
делить ещё и по цене.
"""

from __future__ import annotations

import logging
import statistics

import envcfg

log = logging.getLogger("steam_bot.ruler")

# Источники оценки — они же имена корзин. Совпадают со значениями, которые
# кладутся в CSFloatListing.steam_price_window.
PRICELIST = "last_24h"
CSFLOAT_REFERENCE = "справка CSFloat"

# Во сколько раз источник ЗАВЫШАЕТ низ стакана, пока своих замеров не набрано.
#
# Для прайс-листа 1.13 — не выдумка, а измеренная величина: 20 предметов,
# 2026-08-28, записана в коде как RATIO_EXPLAINABLE_BIAS. Свежие 15 замеров
# 2026-09-13 дали 1.16, то есть цифра держится.
#
# Для справки CSFloat умолчания нет: она занижает, а на сколько — не мерили.
# Ставить наугад хуже, чем не трогать, поэтому 1.0 до первых замеров.
DEFAULT_RATIOS = {
    PRICELIST: envcfg.env_float("RULER_PRICELIST_RATIO", 1.13),
    CSFLOAT_REFERENCE: 1.0,
}
FALLBACK_RATIO = 1.0

# Сколько замеров нужно, чтобы поверить своей медиане больше, чем умолчанию.
MIN_SAMPLES = envcfg.env_int("RULER_MIN_SAMPLES", 8)
# Сколько хранить. Скользящее окно, а не всё подряд: рынок меняется, и замеры
# полугодовой давности про сегодняшний перекос ничего не говорят.
MAX_SAMPLES = envcfg.env_int("RULER_MAX_SAMPLES", 200)
# Границы вменяемости для одного замера. За ними не перекос линейки, а битая
# запись в источнике, и в медиану её пускать незачем.
SANE_LOW, SANE_HIGH = 0.2, 5.0

_samples: dict[str, list[float]] = {}
_dirty = False


def ratio(source: str | None) -> float:
    """Во сколько раз этот источник завышает низ стакана."""
    got = _samples.get(source or "", [])
    if len(got) >= MIN_SAMPLES:
        return statistics.median(got)
    return DEFAULT_RATIOS.get(source or "", FALLBACK_RATIO)


def as_lowest_ask(price: float, source: str | None) -> float:
    """Оценка источника -> то же самое в линейке низа стакана."""
    k = ratio(source)
    return price / k if k > 0 else price


def note(source: str | None, estimate: float | None, real: float | None) -> None:
    """
    Запомнить пару «сырая оценка / реальная цена».

    estimate обязан быть СЫРЫМ значением источника (steam_price_raw), иначе
    коэффициент начнёт отменять сам себя — см. пункт 1 в шапке модуля.
    """
    global _dirty
    if not source or not estimate or not real or real <= 0:
        return
    k = estimate / real
    if not (SANE_LOW <= k <= SANE_HIGH):
        log.info(
            "линейка: замер %s отброшен как выброс — оценка %.2f против реальных %.2f (x%.2f)",
            source, estimate, real, k,
        )
        return
    bucket = _samples.setdefault(source, [])
    bucket.append(k)
    del bucket[:-MAX_SAMPLES]
    _dirty = True


def describe() -> str:
    """Строка для /status и логов: чем меряем и на чём это основано."""
    if not _samples:
        return "линейка: своих замеров нет, беру умолчание x%.2f" % DEFAULT_RATIOS[PRICELIST]
    parts = []
    for source, got in sorted(_samples.items()):
        k = ratio(source)
        source_of_k = "свои" if len(got) >= MIN_SAMPLES else f"умолчание, нужно {MIN_SAMPLES}"
        spread = ""
        if len(got) >= 4:
            lo, hi = min(got), max(got)
            spread = f", разброс {lo:.2f}-{hi:.2f}"
        parts.append(f"{source}: x{k:.2f} ({source_of_k}, замеров {len(got)}{spread})")
    return "линейка — " + "; ".join(parts)


async def load() -> None:
    """Поднять замеры после рестарта. Их потеря — не беда, но и не бесплатно."""
    global _samples, _dirty
    from storage import get_price_ruler

    try:
        saved = await get_price_ruler()
    except Exception:
        log.warning("линейка: замеры не поднялись, начинаю с умолчаний", exc_info=True)
        return
    if not saved:
        return
    _samples = {
        str(k): [float(x) for x in v][-MAX_SAMPLES:]
        for k, v in saved.items()
        if isinstance(v, list)
    }
    _dirty = False
    log.info("линейка: подняты замеры после рестарта. %s", describe())


async def save() -> None:
    """Сохранить, если было что менять. Зовётся после прогона арбитража."""
    global _dirty
    if not _dirty:
        return
    from storage import set_price_ruler

    try:
        await set_price_ruler(_samples)
        _dirty = False
    except Exception:
        log.warning("линейка: замеры не сохранились, повторю после следующего прогона")
