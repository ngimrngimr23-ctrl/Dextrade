"""
Просадки: предметы, торгующиеся заметно дешевле своей месячной нормы.

Чем это отличается от всего остального в боте. /markets и /arbnow ищут разрыв
в ПРОСТРАНСТВЕ: один и тот же предмет прямо сейчас стоит на площадке дешевле,
чем в Steam. Купил — тут же продал, разрыв реализуется мгновенно.

Здесь разрыв во ВРЕМЕНИ: предмет дёшев относительно собственного прошлого.
Чтобы на этом заработать, цена должна вернуться к норме, а она может не
вернуться никогда. Риск принципиально другой, и путать эти две вещи нельзя.

Зато данные бесплатны. Прайс-лист csgotrader и так скачивается для цен
стикеров, и в нём по каждому предмету лежат все окна сразу:

    {"last_24h": 3.84, "last_7d": 5.85, "last_30d": 5.90, "last_90d": 6.20}

Сравнение — арифметика в памяти по 32 тысячам записей: ни одного запроса к
Steam, ни прокси, ни лимитов. Это единственная часть бота, которая работает,
когда всё остальное упирается в 429.

Из этих 32 тысяч сразу вычитаются StatTrak и наклейки — см. is_excluded.

Оговорка про «минимум за месяц». В окнах его нет — там средняя цена
состоявшихся сделок за период. У Steam минимум лежит в pricehistory, который
требует авторизации и режется жёстче priceoverview, то есть на 32 тысячи
предметов недоступен. Поэтому минимум бот копит сам: price_history снимает
срез цен раз в сутки, и через неделю наблюдений у предмета появляется
настоящий минимум за окно. Отбор при этом остаётся на средней — история
приходит только обогащением (поля low, activity_pct), иначе команда молчала бы
до конца первого месяца.
"""

from __future__ import annotations

import logging
from typing import NamedTuple
from urllib.parse import quote

log = logging.getLogger("steam_bot.dips")

MONTH_WINDOW = "last_30d"
WEEK_WINDOW = "last_7d"
TODAY_WINDOW = "last_24h"

# Сколько штук в неделю должно продаваться, чтобы находка вообще имела смысл.
#
# Почему это здесь важнее, чем в /markets. Вся посылка команды — «цена
# вернётся к своей норме». Норма, посчитанная по двум сделкам за месяц, это не
# норма, а две сделки: одна дешёвая продажа сдвигает суточное окно на себя и
# рисует просадку на пустом месте. Выйти из такого предмета потом не выйдет
# вовсе — покупателя нет по построению.
#
# ВАЖНО про единицы. Steam отдаёт объём ТОЛЬКО за сутки (priceoverview,
# поле volume) — недельного числа нет ни у одного доступного источника.
# Поэтому недельный порог считается как суточный × 7. Это экстраполяция с
# одного дня, и она шумная: предмет мог продать ноль сегодня и двадцать
# завтра. Врать об этом нельзя, поэтому в отчёте так и написано.
DEFAULT_MIN_WEEK_VOLUME = 7.0
DAYS_IN_WEEK = 7

# Насколько недельная цена может отставать от месячной, чтобы просадку ещё
# можно было считать свежей.
#
# Смысл проверки. Одного условия «сегодня ниже месяца на N%» мало: под него
# одинаково подходят просадка и падающий нож, а это противоположные вещи.
# Различает их недельное окно:
#
#   сегодня 3.84, неделя 5.85, месяц 5.90  — держалось месяц, упало сегодня
#   сегодня 3.84, неделя 4.60, месяц 5.90  — падает третью неделю подряд
#
# В первом случае неделя почти равна месяцу, во втором — заметно ниже. Порог
# в 10% отделяет обычный шум от установившегося тренда.
MAX_WEEK_DECLINE_PCT = 10.0

# Минимальная цена предмета. На копеечных позициях процент огромен, а деньги
# никакие — та же причина, что и в market_prices.MIN_MARKET_PRICE.
MIN_PRICE = 1.0

# Что не считаем просадкой, сколько бы ни просело.
#
# StatTrak. Тот же отсев, что в сканах вотчлиста (bot._drop_stattrak): счётчик
# убийств сужает круг покупателей, и вернуться к «норме» такому предмету
# нечем — половина его цены держится на моде, а не на самом скине.
#
# Наклейки. В прайс-листе они лежат вперемешку со скинами, и на просадках
# всплывают чаще всех: цена наклейки скачет от вброса капсул и от того, что
# по ней вообще торгуют единицы штук в день. Возврат к месячной средней у
# наклейки не значит ничего — у неё нет floor'а, к которому она обязана
# вернуться.
#
# Проверяем подстрокой и без ™: символ теряется при переносе имён между
# источниками, а «stattrak» в названии обычного скина не встречается.
SKIP_STATTRAK = True
SKIP_STICKERS = True
_STICKER_PREFIX = "Sticker | "


def is_excluded(name: str) -> str | None:
    """Причина, по которой предмет не участвует в поиске просадок. None — участвует."""
    if SKIP_STATTRAK and "stattrak" in name.lower():
        return "StatTrak"
    if SKIP_STICKERS and name.startswith(_STICKER_PREFIX):
        return "наклейка"
    return None


class Dip(NamedTuple):
    """Предмет, просевший относительно месячной нормы."""

    market_hash_name: str
    today: float          # средняя за сутки — самое свежее, что есть на весь каталог
    week: float
    month: float
    drop_pct: float       # насколько сегодня ниже месячной нормы
    week_decline_pct: float   # насколько неделя ниже месяца: мера «ножевости»

    # Ниже — из собственной накопленной истории (price_history). None означает
    # «ещё не накоплено», а не «ноль»: путать эти два состояния нельзя, на
    # объёме продаж бот уже один раз на этом обжёгся.
    low: float | None = None          # настоящий минимум за окно наблюдения
    history_days: int = 0             # сколько срезов за ним стоит
    activity_pct: float | None = None  # доля дней, когда цена менялась

    def is_at_low(self, price: float) -> bool:
        """
        Стоит ли предмет на своём накопленном минимуме ПО ЭТОЙ цене.

        Цена передаётся снаружи, а не берётся из self.today, и это принципиально.
        today — средняя за сутки: предмет мог полдня стоять на минимуме, а к
        вечеру подорожать, и средняя всё равно покажет «на минимуме». Значит
        решать надо по живой цене, а не по дневной. Раньше отбор и показ
        расходились ровно здесь: сортировка шла по суточной, а на экран
        печаталась живая.

        Допуск 0.1% — против округлений, а не «примерно на минимуме».
        """
        return self.low is not None and price <= self.low * 1.001

    def below_low_pct(self, price: float) -> float | None:
        """Насколько эта цена ниже накопленного минимума. Отрицательное — выше."""
        if not self.low:
            return None
        return (self.low - price) / self.low * 100

    def recovery_gain_pct(self, price: float, fee_multiplier: float) -> float:
        """
        Сколько останется чистыми, если цена вернётся к месячной норме.

        Считаем сразу за вычетом комиссии Steam: без неё процент обманывает.
        Просадка в 13% при комиссии 13% — это ровно ноль, а выглядит находкой.

        price — то, по чему покупаем на самом деле (живая цена, если она есть).
        Раньше метод брал self.today, из-за чего им нельзя было пользоваться
        после живой проверки — и в bot.py завелась вторая копия той же
        формулы. Две копии одного правила разъезжаются, вопрос только когда.
        """
        return (self.month * fee_multiplier - price) / price * 100

    @property
    def steam_url(self) -> str:
        return (
            "https://steamcommunity.com/market/listings/730/"
            + quote(self.market_hash_name, safe="")
        )

    def drop_pct_at(self, price: float) -> float:
        """Насколько эта цена ниже месячной нормы."""
        return (self.month - price) / self.month * 100


def week_volume(volume_24h: int | None) -> float | None:
    """
    Оценка недельного объёма по суточному. None — объём неизвестен.

    Отдельной функцией, а не умножением по месту, чтобы допущение было
    названо: недельного объёма Steam не отдаёт, есть только сутки, и всё
    недельное в этом боте — экстраполяция одного дня на семь.
    """
    if volume_24h is None:
        return None
    return volume_24h * DAYS_IN_WEEK


def find_dips(
    details: dict,
    *,
    min_drop_pct: float,
    min_price: float = MIN_PRICE,
    max_price: float | None = None,
    max_week_decline_pct: float = MAX_WEEK_DECLINE_PCT,
    limit: int | None = None,
    history: dict | None = None,
    mature_days: int = 7,
) -> tuple[list[Dip], dict[str, int]]:
    """
    Найти просадки. Возвращает (находки, причины отсева).

    details — то, что отдаёт pricing.get_csgotrader_price_details():
    market_hash_name -> SteamPrice с полем windows.

    history — накопленное самим ботом: market_hash_name -> price_history.Record.
    Отбором оно не управляет, только обогащает находки настоящим минимумом и
    признаком активности. Так сделано намеренно: история набирается неделями,
    и если поставить её условием, команда до конца месяца молчала бы вовсе.

    Отсев считаем по причинам и возвращаем: без разбивки «нашлось три» и
    «нашлось три тысячи» выглядят одинаково непонятно, а понять, слишком ли
    строг порог, по одному числу нельзя.
    """
    history = history or {}
    dropped = {
        "StatTrak": 0,
        "наклейка": 0,
        "нет суточного окна": 0,
        "нет месячного окна": 0,
        "нет недельного окна": 0,
        "дёшево": 0,
        "дорого": 0,
        "просадка ниже порога": 0,
        "падающий нож": 0,
    }
    found: list[Dip] = []

    for name, price in details.items():
        # Первым делом, до всех окон: отсев по типу предмета не зависит от
        # цены, и считать что-то для заведомо исключённого незачем.
        excluded = is_excluded(name)
        if excluded:
            dropped[excluded] += 1
            continue

        windows = getattr(price, "windows", None)
        if not windows:
            continue

        today = windows.get(TODAY_WINDOW)
        if not today:
            # Без суточного окна предмет сегодня не торговался — значит и
            # «просадки сегодня» у него быть не может.
            dropped["нет суточного окна"] += 1
            continue

        month = windows.get(MONTH_WINDOW)
        if not month or month <= 0:
            dropped["нет месячного окна"] += 1
            continue

        if today < min_price:
            dropped["дёшево"] += 1
            continue
        if max_price is not None and today > max_price:
            dropped["дорого"] += 1
            continue

        drop_pct = (month - today) / month * 100
        if drop_pct < min_drop_pct:
            dropped["просадка ниже порога"] += 1
            continue

        # Падающий нож: неделя тоже заметно ниже месяца, то есть предмет
        # снижается давно и «норма» уже не норма.
        #
        # Раньше здесь стояло windows.get(WEEK_WINDOW, month) — при отсутствии
        # недельного окна подставлялся месяц, спад выходил нулевым, и предмет
        # ВСЕГДА проходил проверку. То есть главный защитный фильтр модуля
        # молча выключался ровно там, где данных не хватает. Отсутствие данных
        # означает «не знаю», а не «всё хорошо»: без недели отличить просадку
        # от обвала нечем, и находка такой не считается.
        week = windows.get(WEEK_WINDOW)
        if not week or week <= 0:
            dropped["нет недельного окна"] += 1
            continue
        week_decline = (month - week) / month * 100
        if week_decline > max_week_decline_pct:
            dropped["падающий нож"] += 1
            continue

        # Накопленное по этому предмету. Незрелую запись не подставляем вовсе:
        # «минимум за два дня» — это не минимум, а меньшая из двух цен, и
        # показывать её как минимум значит врать.
        record = history.get(name)
        mature = record is not None and record.is_mature(mature_days)

        found.append(Dip(
            market_hash_name=name,
            today=today,
            week=week,
            month=month,
            drop_pct=drop_pct,
            week_decline_pct=week_decline,
            low=record.low if mature else None,
            history_days=record.days if record is not None else 0,
            activity_pct=record.activity_pct if mature else None,
        ))

    # Порядок только по величине просадки. Раньше первым ключом шло «стоит на
    # своём минимуме», но здесь этого знать НЕЛЬЗЯ: признак считался от
    # суточной средней, а решает живая цена, которой на этом этапе ещё нет.
    # Получалось, что список упорядочен по одному числу, а размечен на экране
    # по другому. Сортировка «на минимуме сначала» переехала в bot.py — туда,
    # где живые цены уже получены.
    found.sort(key=lambda d: d.drop_pct, reverse=True)
    log.info(
        "dips: просмотрено %d, прошло %d. Отсеяно: %s",
        len(details), len(found),
        ", ".join(f"{k} {v}" for k, v in dropped.items() if v) or "ничего",
    )
    return (found[:limit] if limit else found), dropped
