"""
Что попадёт в один прогон вотчлиста: приоритетные предметы и кусок остальных.

Зачем это вообще нужно. Профиль прогона показал, что время цикла равно
(число предметов × пауза между запросами) с точностью до долей процента, и
никакие воркеры, кэши и батчи на него не влияют. На 541 предмете это 36 минут,
то есть каждый предмет проверяется раз в ~38 минут.

Отсюда прямое следствие, из-за которого «список приоритетных» сам по себе
бесполезен: если добавить 80 горячих предметов СВЕРХ пятисот сорока, цикл
станет 41 минуту, и горячие будут проверяться раз в 41 минуту — хуже, чем
было. Бюджет запросов фиксирован, и приоритет означает не «добавить», а
«перераспределить»: горячие каждый цикл, остальные по кругу.

    цикл = все приоритетные + N из остальных

    80 приоритетных + 60 из 461 = 140 предметов = 9.3 мин на цикл
      приоритетные:  раз в ~11 мин  (вместо 38)
      остальные:     раз в ~85 мин  (461 / 60 = 8 циклов)

Хвост при этом проверяется реже — это не побочный эффект, а суть размена, и
говорить о нём надо вслух (см. describe_cycle).

Модуль намеренно ничего не знает ни про бота, ни про хранилище: на вход список
и позиция курсора, на выход — что сканировать и куда сдвинуть курсор.
"""

from __future__ import annotations

# Сколько предметов из «остальных» брать в один цикл, если не задано иное.
#
# Шестьдесят выбрано не из теории: при 80 приоритетных это даёт цикл около
# девяти минут — то есть приоритетные проверяются вчетверо чаще, чем сейчас, а
# полный круг по остальным занимает полтора часа. Обе величины остаются
# осмысленными. Значение настраивается, потому что правильное зависит от
# размера списков, а он у всех свой.
DEFAULT_COLD_PER_CYCLE = 60


# Сколько предметов Steam пропускает с одного адреса, прежде чем ответить 429.
#
# Число не выдумано: живой лог показывает, что прогон падает РОВНО на сотом
# предмете, каждый раз. Один предмет — это один запрос к /render/
# (DEFAULT_MAX_LISTINGS=100 подобран так, чтобы хватало одной страницы),
# значит потолок адреса — около сотни запросов на окно.
#
# Берём с запасом: упереться в потолок дорого. 429 не просто обрывает прогон,
# он ставит кулдаун с удвоением и портит следующие попытки, так что десяток
# предметов в запас окупается многократно.
DEFAULT_MAX_ITEMS_PER_CYCLE = 90


def split_cycle(
    plan: list, hot_names: set, cursor: int, cold_per_cycle: int | None,
    max_items: int | None = None,
) -> tuple[list, int]:
    """
    Разделить план прогона на «этот цикл» и «в следующий раз».

    plan — список записей, у каждой первым элементом имя предмета (в боте это
    кортеж (имя, проверять_стикеры, проверять_флоат)). Работаем с записями
    целиком, а не с именами: флаги проверки должны доехать до сканера ровно
    те же, что были бы без ротации.

    Возвращает (что сканировать сейчас, новый курсор).

    cold_per_cycle=None или пустой hot_names означают «ротации нет, сканируем
    всё» — то есть в точности прежнее поведение. Это важно: пока человек не
    завёл приоритетный список, ничего меняться не должно.
    """
    if not hot_names or not cold_per_cycle or cold_per_cycle <= 0:
        return _fit_budget(list(plan), cursor, max_items)

    hot = [entry for entry in plan if entry[0] in hot_names]
    cold = [entry for entry in plan if entry[0] not in hot_names]

    # Бюджет адреса важнее приоритетов: если приоритетных больше, чем Steam
    # пропускает за окно, «каждый цикл все горячие» невыполнимо в принципе —
    # прогон просто умрёт на сотом. Тогда крутим окно и по ним тоже.
    if max_items is not None and len(hot) >= max_items:
        return _fit_budget(hot, cursor, max_items)

    room = None if max_items is None else max_items - len(hot)
    if room is not None and cold_per_cycle > room:
        cold_per_cycle = max(room, 0)

    if not cold or not cold_per_cycle:
        return hot, 0
    if cold_per_cycle >= len(cold):
        return hot + cold, 0

    # Курсор мог остаться от списка, который с тех пор укоротили.
    start = cursor % len(cold)
    take = cold[start:start + cold_per_cycle]
    if len(take) < cold_per_cycle:
        # Дошли до конца — добираем с начала. Иначе последний цикл круга был бы
        # короче остальных, и предметы в хвосте списка проверялись бы реже
        # прочих просто из-за своего места в нём.
        take += cold[:cold_per_cycle - len(take)]
    return hot + take, (start + cold_per_cycle) % len(cold)


def _fit_budget(plan: list, cursor: int, max_items: int | None) -> tuple[list, int]:
    """
    Урезать план до бюджета адреса, прокручивая окно по кругу.

    Курсор общий с ротацией «остальных»: заводить второй ради того же самого
    движения по кругу незачем, а путать их — верный способ получить предмет,
    который не проверяется никогда.
    """
    if max_items is None or len(plan) <= max_items:
        return plan, 0
    start = cursor % len(plan)
    window = plan[start:start + max_items]
    if len(window) < max_items:
        window += plan[:max_items - len(window)]
    return window, (start + max_items) % len(plan)


def describe_cycle(
    hot_count: int, cold_count: int, cold_per_cycle: int | None,
    request_interval: float, gap_minutes: float,
) -> list[str]:
    """
    Человеческое описание расписания: раз во сколько что проверяется.

    Считается по тождеству «время цикла = предметы × пауза», проверенному на
    живых прогонах с точностью 0.2%. Поэтому это не оценка, а расчёт.
    """
    total = hot_count + cold_count
    if not hot_count or not cold_per_cycle or cold_per_cycle <= 0:
        full = total * request_interval / 60
        return [
            f"Ротации нет: каждый цикл проверяются все {total} предмет(ов).",
            f"Цикл ≈ {full:.0f} мин, каждый предмет — раз в "
            f"{full + gap_minutes:.0f} мин.",
        ]

    per_cycle = hot_count + min(cold_per_cycle, cold_count)
    cycle_min = per_cycle * request_interval / 60
    period = cycle_min + gap_minutes
    cycles_for_full = -(-cold_count // cold_per_cycle) if cold_count else 1
    was = total * request_interval / 60 + gap_minutes

    return [
        f"Цикл: {hot_count} приоритетных + {min(cold_per_cycle, cold_count)} "
        f"из остальных ({cold_count}) = {per_cycle} предметов ≈ {cycle_min:.0f} мин.",
        f"  приоритетные — раз в {period:.0f} мин",
        f"  остальные — раз в {period * cycles_for_full:.0f} мин "
        f"(полный круг за {cycles_for_full} цикл(ов))",
        f"Без приоритетного списка все {total} проверялись бы раз в {was:.0f} мин.",
    ]
